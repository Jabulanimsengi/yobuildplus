// Helper function to get all cities flattened
export function getAllLocations() {
    return Object.values(locationsData).flat();
}

// Helper to check if a location exists and return its province
export function findLocation(city: string) {
    for (const [province, cities] of Object.entries(locationsData)) {
        if (cities.map(c => c.toLowerCase()).includes(city.toLowerCase())) {
            return { city, province };
        }
    }
    return null;
}
